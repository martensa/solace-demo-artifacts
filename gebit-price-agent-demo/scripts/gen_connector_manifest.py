#!/usr/bin/env python3
"""Write the `manifest:` block of the gpos MCP connectors (spec 8.5).

A connector applied with `sam config apply` keeps no tool list unless it
carries a manifest; workflow tool nodes then cannot bind (G0-01). With a
manifest it registers exactly these tools without live discovery. The block is
a YAML block list with the schemas as JSON flow (a `|` string is refused).

  # all six connectors from the image, locally (no cluster, DB, bus or GEBIT mount)
  scripts/gen_connector_manifest.py --from-image registry.solace.lab/gpos-demo/gpos-demo:0.1.3

  # one connector from a saved tools/list
  python -m gposdemo.wws --dump-tools > wws.json
  scripts/gen_connector_manifest.py --tools-json wws.json --out mesh/connectors/gpos-wws-api.yaml

Contract checks (spec 8.1-8.4): the tool names of every connector are exactly
the spec's; workflow tools (gpos-booth-tools, gpos-price-gate, gpos-price-apply)
carry an outputSchema, agent tools (gpos-wws-api, gpos-loyalty-api,
gpos-pos-api) carry none.
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import Any

import yaml

from opslib import DEMO_DIR, OpsError

INDENT = "      "
PLACEHOLDER_MARK = "# PLACEHOLDER"
GENERATED_MARK = "# GENERATED by scripts/gen_connector_manifest.py"


@dataclass(frozen=True)
class ConnectorSpec:
    """One connector file, the service that serves its tools and the contract."""

    path: str
    service: str            # module below gposdemo, for --dump-tools / ui.ctl tools-list
    workflow_tools: bool    # True: outputSchema required, False: forbidden
    tools: tuple[str, ...]


BOOTH_TOOLS = ("assess_event", "close_review", "check_proposal", "note_event",
               "note_evidence", "prepare_review", "raise_basket_review", "record_outcome",
               "stage_proposal")
CONNECTORS = (
    ConnectorSpec("mesh/connectors/gpos-booth-tools.yaml", "engine", True, BOOTH_TOOLS),
    ConnectorSpec("mesh/connectors/gpos-price-gate.yaml", "engine.gate", True,
                  ("apply_price",)),
    ConnectorSpec("mesh/fallback/connectors/gpos-price-apply.yaml", "engine.gate", True,
                  ("apply_price",)),
    ConnectorSpec("mesh/connectors/gpos-wws-api.yaml", "wws", False,
                  ("get_article", "get_sales_performance", "get_season_info")),
    ConnectorSpec("mesh/connectors/gpos-loyalty-api.yaml", "loyalty", False,
                  ("get_member_profile", "get_purchase_behaviour")),
    ConnectorSpec("mesh/connectors/gpos-pos-api.yaml", "pos", False,
                  ("get_transaction", "get_till_status")),
)
CTL_NAMES = {"engine": "engine", "engine.gate": "gate", "wws": "wws", "loyalty": "loyalty",
             "pos": "pos"}


def tool_list(payload: Any) -> list[dict]:
    """tools/list as printed by --dump-tools / ui.ctl tools-list: a list, or an
    object with `tools` (JSON-RPC result shape)."""
    if isinstance(payload, dict):
        payload = payload.get("result", payload).get("tools")
    if not isinstance(payload, list) or not all(isinstance(t, dict) for t in payload):
        raise OpsError("tools/list: expected a list of tool objects")
    return payload


def build_entries(tools: list[dict]) -> list[dict]:
    """The manifest entries: name, description (whitespace folded), inputSchema,
    outputSchema when the server advertises one; sorted by name."""
    entries = []
    for tool in sorted(tools, key=lambda t: t["name"]):
        entry = {"name": tool["name"],
                 "description": " ".join((tool.get("description") or "").split()),
                 "inputSchema": tool.get("inputSchema") or {"type": "object"}}
        if tool.get("outputSchema"):
            entry["outputSchema"] = tool["outputSchema"]
        entries.append(entry)
    return entries


def contract_errors(spec: ConnectorSpec, entries: list[dict]) -> list[str]:
    errors = []
    names = tuple(sorted(e["name"] for e in entries))
    if names != tuple(sorted(spec.tools)):
        errors.append(f"{spec.path}: tools {names} != spec {tuple(sorted(spec.tools))}")
    for entry in entries:
        has_output = "outputSchema" in entry
        if spec.workflow_tools and not has_output:
            errors.append(f"{spec.path}: workflow tool {entry['name']} without outputSchema")
        if not spec.workflow_tools and has_output:
            errors.append(f"{spec.path}: agent tool {entry['name']} has an outputSchema "
                          "(spec 8.1: text content only)")
        if "inputSchema" not in entry:
            errors.append(f"{spec.path}: {entry['name']} without inputSchema")
    return errors


def render_block(entries: list[dict], service: str) -> str:
    lines = ["    manifest:",
             f"{INDENT}{GENERATED_MARK} -- do not edit",
             f"{INDENT}# source: python -m gposdemo.{service} --dump-tools"]
    for entry in entries:
        lines.append(f"{INDENT}- name: {json.dumps(entry['name'])}")
        lines.append(f"{INDENT}  description: "
                     f"{json.dumps(entry['description'], ensure_ascii=False)}")
        for key in ("inputSchema", "outputSchema"):
            if key in entry:
                lines.append(f"{INDENT}  {key}: {json.dumps(entry[key], ensure_ascii=False)}")
    return "\n".join(lines) + "\n"


def replace_block(text: str, block: str) -> str:
    """Swap the `    manifest:` block (up to the next key at indent <= 4, e.g.
    `    hil:`) for `block`; everything else stays byte for byte."""
    lines = text.splitlines(keepends=True)
    try:
        start = next(i for i, line in enumerate(lines) if line.startswith("    manifest:"))
    except StopIteration as exc:
        raise OpsError("no `    manifest:` block found") from exc
    end = start + 1
    while end < len(lines) and (not lines[end].strip() or lines[end].startswith(INDENT)):
        end += 1
    return "".join(lines[:start]) + block + "".join(lines[end:])


def manifest_entries(path: Path) -> list[dict]:
    return manifest_entries_from_text(path.read_text(encoding="utf-8"))


def manifest_entries_from_text(text: str) -> list[dict]:
    return list(yaml.safe_load(text)["spec"]["values"].get("manifest") or [])


def is_placeholder(path: Path) -> bool:
    return PLACEHOLDER_MARK in path.read_text(encoding="utf-8")


def write_connector(spec: ConnectorSpec, tools: list[dict], root: Path = DEMO_DIR) -> None:
    entries = build_entries(tools)
    errors = contract_errors(spec, entries)
    if errors:
        raise OpsError("; ".join(errors))
    path = root / spec.path
    text = replace_block(path.read_text(encoding="utf-8"), render_block(entries, spec.service))
    if manifest_entries_from_text(text) != entries:
        raise OpsError(f"{spec.path}: generated block does not parse back")
    path.write_text(text, encoding="utf-8")
    print(f"{spec.path}: {len(entries)} tools ({', '.join(e['name'] for e in entries)})")


def dump_tools(image: str, service: str) -> list[dict]:
    """`docker run --rm IMAGE python -m gposdemo.<svc> --dump-tools` (spec 2.4:
    no DB, bus or GEBIT descriptors needed)."""
    proc = subprocess.run(["docker", "run", "--rm", image, "python", "-m",
                           f"gposdemo.{service}", "--dump-tools"],
                          capture_output=True, text=True, timeout=180, check=False)
    if proc.returncode != 0:
        raise OpsError(f"--dump-tools of gposdemo.{service} failed: "
                       f"{' '.join(proc.stderr.split())[-300:]}")
    return tool_list(json.loads(proc.stdout))


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    src = ap.add_mutually_exclusive_group(required=True)
    src.add_argument("--from-image", metavar="IMAGE", help="all six connectors from this image")
    src.add_argument("--tools-json", type=Path, help="tools/list JSON of one service")
    ap.add_argument("--out", type=Path, help="connector YAML for --tools-json")
    args = ap.parse_args(argv)
    try:
        if args.tools_json:
            if not args.out:
                ap.error("--tools-json needs --out")
            rel = args.out.resolve().relative_to(DEMO_DIR).as_posix()
            spec = next((c for c in CONNECTORS if c.path == rel), None)
            if spec is None:
                raise OpsError(f"{rel} is not a gpos connector")
            write_connector(spec, tool_list(json.loads(args.tools_json.read_text("utf-8"))))
            return 0
        cache: dict[str, list[dict]] = {}
        out_dir = DEMO_DIR / "build" / "tools"
        out_dir.mkdir(parents=True, exist_ok=True)
        for spec in CONNECTORS:
            if spec.service not in cache:
                cache[spec.service] = dump_tools(args.from_image, spec.service)
                (out_dir / f"{spec.service}.json").write_text(
                    json.dumps(cache[spec.service], ensure_ascii=False, indent=1), "utf-8")
            write_connector(spec, cache[spec.service])
        return 0
    except (OpsError, ValueError, KeyError) as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main())
